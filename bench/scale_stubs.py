"""Write (or remove) one DAG file per synthetic project size and mode under dags/scale_generated/.

One DAG per file matters for the numbers: Airflow re-parses a task's DAG file before running it, so a file
holding all twelve scale DAGs added ~1-2 s to every task. `just scale` writes the stubs, runs, then removes them.

    python bench/scale_stubs.py write 10 50 200
    python bench/scale_stubs.py clean
"""

from __future__ import annotations

import sys
from pathlib import Path

DIR = Path(__file__).parents[1] / "dags" / "scale_generated"
MODES = ("build", "watcher", "watcher_exec", "kubernetes_exec", "kubernetes")
STUB = '''"""scale_{n}_{mode}: generated by bench/scale_stubs.py for `just scale`; removed afterwards."""

# One DAG per file: airflow re-parses a task's DAG file before running it.
from demo_ops.cosmos_dags import scale_dag

dag = scale_dag({n}, "{mode}")
'''

if __name__ == "__main__":
    action, sizes = sys.argv[1], [int(n) for n in sys.argv[2:]]
    for stub in DIR.glob("scale_*.py"):
        stub.unlink()
    if action == "write":
        DIR.mkdir(parents=True, exist_ok=True)
        for n in sizes:
            for mode in MODES:
                (DIR / f"scale_{n}_{mode}.py").write_text(STUB.format(n=n, mode=mode))
        print(f"wrote {len(sizes) * len(MODES)} DAG stubs in {DIR}")
